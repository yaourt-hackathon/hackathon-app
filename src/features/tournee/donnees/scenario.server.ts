// Scénario de la démo (ADR 0008), côté serveur seulement. Règles, vérifiées
// par scenario.server.test.ts :
// - un événement copié de l'API garde son id et son contenu (EVT-001) ; un
//   événement propre à la démo prend un id DEMO-xx et le statut « test » ;
// - une marque réelle n'a que des produits réels d'Open Beauty Facts (code,
//   nom et ingrédients lus dans les données de l'équipe data) ; un produit
//   inventé (code 200…, réservé à l'usage interne) appartient à une entreprise
//   inventée, dont le nom le dit ;
// - le CRM est fictif : Cattier, prospect dans l'API, est ici un client ;
// - un fait cite sa source, une question finit par « ? ». Les faits sont dits
//   au client (« Votre… », maquette v1) ; EVT-001 garde ses nombres et ses
//   produits de l'API au commit data 05991a7 (l'API a grandi depuis), mais
//   ses phrases sont réécrites pour la démo.
// `origine_textes` vaut « gabarit » : l'API n'a pas de valeur « préparé » ; en
// mode démo, l'écran dit que tout texte a été préparé par l'équipe.

type EvenementScenario = Omit<Evenement, 'nb_comptes_a_appeler'>;
type CompteScenario = Omit<Compte, 'date_maj' | 'crm_fictif' | 'evenements'>;
type ProduitScenario = Omit<
  ProduitTouche,
  'niveau' | 'elements_directs' | 'elements_indices'
> & {
  /** Liste d'ingrédients de l'étiquette (INCI), quand on l'a. */
  ingredients?: string;
};
type ProduitAppel = Pick<
  ProduitTouche,
  'code_barre' | 'niveau' | 'elements_directs' | 'elements_indices'
>;
type AppelScenario = Omit<
  Appel,
  'nom_compte' | 'statut' | 'nb_produits_analyses'
> & { evenement_id: string; produits: ProduitAppel[] };

export interface Scenario {
  date_maj: string;
  evenements: EvenementScenario[];
  comptes: CompteScenario[];
  produits: ProduitScenario[];
  appels: AppelScenario[];
}

